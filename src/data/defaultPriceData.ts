/**
 * Normalizes raw sheet matrix into flat individual records for fast search and filtering
 */
export function normalizeMatrix(matrix: RawMatrixRow[]): NormalizedPriceRecord[] {
  const records: NormalizedPriceRecord[] = [];

  matrix.forEach((row, rowIndex) => {
    SHEET_COLUMNS.forEach((col) => {
      const priceVal = row.prices[col.key];
      // Note: null represents blank / unavailable cell. Never convert to 0!
      records.push({
        id: `${rowIndex}_${col.category}_${col.feeType}`,
        serviceName: row.serviceName,
        category: col.category,
        feeType: col.feeType,
        price: priceVal !== undefined && priceVal !== null ? Number(priceVal) : null,
      });
    });
  });

  return records;
}

export const INITIAL_NORMALIZED_RECORDS: NormalizedPriceRecord[] = normalizeMatrix(RAW_SOURCE_MATRIX);
